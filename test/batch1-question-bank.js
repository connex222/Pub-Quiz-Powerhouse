'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const pub=path.join(__dirname,'../public');
const source=fs.readFileSync(path.join(pub,'question-banks/quizdemon-batch1.js'),'utf8');
const ctx={window:{}};
vm.runInNewContext(source,ctx);
const quizzes=ctx.window.PQP_IMPORTED_QUIZZES;
assert.equal(quizzes.length,12,'12 supplied PDFs');
const allRounds=quizzes.flatMap(q=>q.rounds);
const qs=allRounds.flatMap(r=>r.questions);
const tbs=quizzes.flatMap(q=>q.tiebreakers);
assert.equal(allRounds.length,72);
assert.equal(qs.length,594,'594 prompts');
assert.equal(qs.reduce((n,q)=>n+q.pts,0),600,'600 scoring slots');
assert.equal(tbs.length,24);
assert.equal(new Set(qs.map(q=>q.id)).size,594,'durable unique IDs');
assert.deepEqual([...new Set(quizzes.map(q=>q.title))].length,12);
assert.equal(allRounds.filter(r=>r.type==='letters').length,12);
assert(allRounds.every(r=>r.questions.length && ['typed','written'].includes(r.mode)));
assert(qs.every(q=>q.q && q.a && q.pts>=1 && q.pts<=4));
assert(quizzes.find(q=>q.title==='QuizDemon 337').rounds[3].questions.map(q=>q.pts).join(',')==='1,2,3,4');
const html=fs.readFileSync(path.join(pub,'index.html'),'utf8');
assert(html.includes('src="/question-banks/quizdemon-batch1.js"'));
const match=html.match(/const BUILTIN_QUIZZES = (\[[^\n]+?\].concat\(window.PQP_IMPORTED_QUIZZES \|\| \[\]\));/);
assert(match,'original library plus batch1 must be concatenated');
const all=vm.runInNewContext(match[1],ctx);
assert.equal(all.length,16,'4 existing + 12 imported quizzes');
assert.equal(all.slice(0,4).reduce((n,q)=>n+q.rounds.reduce((a,r)=>a+r.questions.length,0),0),200);
assert.equal(all.slice(4).reduce((n,q)=>n+q.rounds.reduce((a,r)=>a+r.questions.length,0),0),594);
assert.equal(qs.find(q=>q.id==='QD228-Q18').a,'Illinois');
assert.equal(qs.find(q=>q.id==='QD101-Q10').a,'Sharron Davies');
assert.equal(qs.find(q=>q.id==='QD344-Q12').a,'Stanley');
assert(/immortal spiritual beings/i.test(qs.find(q=>q.id==='QD346-Q24').q));
const first=all.find(q=>q.title==='QuizDemon 101');
assert.equal(first.rounds[0].mystery,'GEOFF CAPES');
assert.equal(first.rounds[0].questions.length,10);
assert.equal(first.rounds[0].questions[7].a,'Palindrome','preserve Link-a-Letter duplicate in puzzle context');
assert.equal(first.rounds[0].mode,'written');
assert.equal(first.rounds[2].mode,'typed');
assert.equal(all.find(q=>q.title.startsWith('QuizDemon 281')).rounds.length,6);
// JS parser syntax check for main inline script, independent of missing Socket.io dependency.
const scripts=[...html.matchAll(/<script(?:\s[^>]*)?>([\s\S]*?)<\/script>/g)].map(m=>m[1]).filter(x=>x.trim());
assert.equal(scripts.length,1);
new Function(scripts[0]);
console.log('PASS: original library + 12 source quizzes, 72 rounds, 594 prompts, 600 scoring slots, 24 tie-breakers, special-order puzzles, corrected flags and HTML syntax');
