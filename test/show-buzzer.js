'use strict';
const assert=require('node:assert/strict');
const b=require('../public/show-buzzer.js');
const ids=['a','b','c'];
let s={open:true,awarded:false,revealed:false,order:[]};
assert.equal(b.canAccept(s,'a',ids),true);
assert.equal(b.canAccept(s,'non-team',ids),false);
s.order.push({id:'a',st:'wait'}); s.open=false;
assert.equal(b.active(s).id,'a');
assert.equal(b.canAccept(s,'b',ids),false,'atomic first claim locks challengers');
s.order[0].st='wrong'; s.open=true;
assert.equal(b.active(s),null);
assert.equal(b.canAccept(s,'a',ids),false,'wrong answer cannot re-buzz');
assert.equal(b.canAccept(s,'b',ids),true);
assert.deepEqual(b.remaining(s,ids),['b','c']);
assert.equal(b.canReopen(s,ids,0,false),true,'untimed round continues');
assert.equal(b.canReopen(s,ids,0,true),false,'expired timer blocks reopening');
assert.equal(b.canReopen(s,ids,1,true),true);
s.order.push({id:'b',st:'wait'});
assert.equal(b.canReopen(s,ids,10,true),false,'active claim cannot be bypassed');
s.order[1].st='right';s.awarded=true;
assert.equal(b.canAccept(s,'c',ids),false);
assert.equal(b.canReopen(s,ids,30,true),false);
s={open:false,awarded:false,revealed:false,order:[{id:'a',st:'wrong'},{id:'b',st:'wrong'},{id:'c',st:'wrong'}]};
assert.equal(b.canReopen(s,ids,20,true),false,'all teams exhausted');
assert.deepEqual(b.oneActive([{id:'a',st:'wait'},{id:'b',st:'wait'},{id:'c',st:'wrong'}]).map(x=>x.id),['a','c']);
console.log('Exclusive Show buzzer state tests: passed');
